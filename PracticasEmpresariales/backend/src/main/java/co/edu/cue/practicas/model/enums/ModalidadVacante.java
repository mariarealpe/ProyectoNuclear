package co.edu.cue.practicas.model.enums;

/**
 * Modalidad de trabajo de la vacante de práctica.
 * Define dónde realiza el estudiante sus actividades laborales.
 */
public enum ModalidadVacante {

    /** El estudiante asiste todos los días a las instalaciones de la empresa. */
    PRESENCIAL,

    /** El estudiante trabaja desde casa o cualquier ubicación remota. */
    REMOTO,

    /** Combinación de días presenciales y remotos. */
    HIBRIDO
}
