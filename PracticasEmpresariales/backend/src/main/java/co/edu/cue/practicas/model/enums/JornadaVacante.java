package co.edu.cue.practicas.model.enums;

/**
 * Jornada laboral de la vacante.
 * Indica la dedicación horaria que se le exige al estudiante practicante.
 */
public enum JornadaVacante {

    /** Jornada laboral completa, generalmente 40 horas semanales. */
    TIEMPO_COMPLETO,

    /** Media jornada, generalmente 20 horas semanales — apta para estudiantes con carga académica. */
    MEDIO_TIEMPO
}
