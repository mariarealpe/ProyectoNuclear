package co.edu.cue.practicas.model.enums;

/**
 * Tipos de firmantes de documentos.
 * 
 * Para el convenio de práctica se requieren 3 firmas:
 * 1. Coordinador de Prácticas (institución)
 * 2. Tutor Empresarial (empresa)
 * 3. Estudiante (practicante)
 */
public enum TipoFirmante {
    COORDINADOR,         // Coordinador de Prácticas (institución)
    TUTOR_EMPRESARIAL,   // Tutor Empresarial (empresa)
    ESTUDIANTE           // Estudiante practicante
}
